"""Generate Rust range tables for Sail's JDK 17 Locale.ROOT lowercase port from probe.json
(RootLowercaseProbe.java on Oracle JDK 17.0.8). Usage: generate_tables.py probe.json out.rs"""
import json, sys, hashlib
d = json.load(open(sys.argv[1]))
def S(k):
    r = set(); [r.update(range(a, b + 1)) for a, b in d[k]]; return r
def ranges(s):
    out = []; s = sorted(s); i = 0
    while i < len(s):
        a = b = s[i]
        while i + 1 < len(s) and s[i + 1] == b + 1: b = s[i + 1]; i += 1
        out.append((a, b)); i += 1
    return out
conn = S('sigma_connector')
cased_after = S('sigma_non_final_after')
cased_before = S('sigma_final_after_alone')
word_after = S('sigma_non_final_after_internal') - conn
allcp = set(range(0x110000)) - set(range(0xD800, 0xE000))
word_before = (allcp - S('sigma_non_final_before')) - conn
letter_before = S('letter_before') - conn
letter_after = S('letter_after') - conn
number_before = S('number_before') - conn - cased_after  # the probe cannot see past a cased X; a cased X never precedes a number connector in a decision
number_after = S('number_after') - conn
number_conn = S('number_connector') - word_after - number_after
tables = {
 'CASED_AFTER': cased_after, 'CASED_BEFORE': cased_before,
 'WORD_AFTER': word_after, 'WORD_BEFORE': word_before,
 'LETTER_BEFORE': letter_before, 'LETTER_AFTER': letter_after,
 'NUMBER_BEFORE': number_before, 'NUMBER_AFTER': number_after,
 'CONNECTORS': conn, 'NUMBER_CONNECTORS': number_conn,
}
src = hashlib.sha256(open('RootLowercaseProbe.java','rb').read()).hexdigest()
lines = [
 "//! Generated by generate_tables.py from RootLowercaseProbe.java (SHA-256 %s)" % src,
 "//! run on %s (%s). Each table is a sorted list of inclusive code point ranges" % (d['java_runtime_version'], d['java_vendor']),
 "//! observed through `String.toLowerCase(Locale.ROOT)` with a Greek capital sigma",
 "//! and fixed neighbours; see `root_lowercase.rs` for what each class means.",
 "//! Do not edit by hand.", "",
 "#[cfg(test)]", "pub(super) const SCALAR_FNV1A64: u64 = 0x%s;" % d["scalar_fnv1a64"], "",
]
for name, s in tables.items():
    rs = ranges(s)
    lines.append("#[rustfmt::skip]")
    lines.append("pub(super) const %s: &[(u32, u32)] = &[" % name)
    row = []
    for a, b in rs:
        row.append("(0x%X, 0x%X)" % (a, b))
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ","); row = []
    if row: lines.append("    " + ", ".join(row) + ",")
    lines.append("];"); lines.append("")
open(sys.argv[2], "w").write("\n".join(lines).rstrip("\n") + "\n")
if len(sys.argv) > 3:
    json.dump({'java_runtime_version': d['java_runtime_version'], 'java_vendor': d['java_vendor'], 'probe_sha256': src,
               'scalar_fnv1a64': d['scalar_fnv1a64'], 'strings': d['strings']}, open(sys.argv[3], 'w'), indent=0)
print({k: len(ranges(v)) for k, v in tables.items()}, 'lines', len(lines))
# simulate
simple = {a: b for a, b in d['simple_lowercase']}
def connector_internal(cps, j):
    if j == 0 or j + 1 >= len(cps): return False
    p, n, c = cps[j-1], cps[j+1], cps[j]
    if c in conn and p in letter_before and n in letter_after: return True
    return c in number_conn and p in number_before and n in number_after
def is_final(cps, i):
    j = i - 1
    while j >= 0:
        x = cps[j]
        if x in conn or x in number_conn:
            if connector_internal(cps, j): j -= 1; continue
            return False
        if x in cased_before: break
        if x in word_before: j -= 1; continue
        return False
    if j < 0: return False
    k = i + 1
    while k < len(cps):
        x = cps[k]
        if x in conn or x in number_conn:
            if connector_internal(cps, k): k += 1; continue
            return True
        if x in cased_after: return False
        if x in word_after: k += 1; continue
        return True
    return True
def lower(cps):
    out = []
    for i, c in enumerate(cps):
        if c == 0x3A3: out.append(0x3C2 if is_final(cps, i) else 0x3C3)
        elif c == 0x130: out += [0x69, 0x307]
        else: out.append(simple.get(c, c))
    return out
bad = 0
for s in d['strings']:
    got = lower(s['input'])
    if got != s['lower']:
        bad += 1; print('MISMATCH', ''.join(map(chr, s['input'])).encode('unicode_escape').decode(), 'java', ''.join(map(chr, s['lower'])).encode('unicode_escape').decode(), 'model', ''.join(map(chr, got)).encode('unicode_escape').decode())
print('designed', len(d['strings']), 'mismatches', bad)
