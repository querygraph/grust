"""Generate Sail's root_lowercase_tables.rs from word-break-tables.json (WordBreakTablesDump.java by reflection on
the JDK's ROOT word BreakIterator) and probe.json (RootLowercaseProbe.java scalar hash), and merge the oracle
fixture. Usage: generate_break_tables.py word-break-tables.json probe.json context-sets.json oracle.json out.rs out.json"""
import hashlib, json, sys
tables = json.load(open(sys.argv[1])); probe = json.load(open(sys.argv[2])); context = json.load(open(sys.argv[3])); oracle = json.load(open(sys.argv[4]))
def sha(p): return hashlib.sha256(open(p, 'rb').read()).hexdigest()
lines = [
 "//! Generated by generate_break_tables.py; do not edit by hand.",
 "//! Word-break tables: WordBreakTablesDump.java (SHA-256 %s) read them by" % sha("WordBreakTablesDump.java"),
 "//! reflection from `BreakIterator.getWordInstance(Locale.ROOT)` on %s," % tables["java_runtime_version"],
 "//! class %s, rule-data checksum 0x%s: the compiled" % (tables["iterator_class"], tables["checksum"]),
 "//! forward and backward state tables, their end and lookahead flags, the",
 "//! category of every code point as inclusive ranges, and the code points",
 "//! `ConditionalSpecialCasing.isCased` accepts, from `Character.getType`.",
 "",
 "pub(super) const NUM_CATEGORIES: usize = %d;" % tables["num_categories"],
 "",
]
def emit(name, ty, values, per_line, fmt=str):
    lines.append("#[rustfmt::skip]"); lines.append("pub(super) const %s: &[%s] = &[" % (name, ty))
    row = []
    for v in values:
        row.append(fmt(v))
        if len(row) == per_line: lines.append("    " + ", ".join(row) + ","); row = []
    if row: lines.append("    " + ", ".join(row) + ",")
    lines.append("];"); lines.append("")
emit("STATE_TABLE", "i16", tables["state_table"], 22)
emit("BACKWARDS_STATE_TABLE", "i16", tables["backwards_state_table"], 22)
emit("END_STATES", "bool", tables["end_states"], 20, lambda v: "true" if v else "false")
emit("LOOKAHEAD_STATES", "bool", tables["lookahead_states"], 20, lambda v: "true" if v else "false")
emit("CATEGORY_RANGES", "(u32, u32, i8)", tables["category_ranges"], 3, lambda r: "(0x%X, 0x%X, %d)" % (r[0], r[1], r[2]))
emit("CASED_RANGES", "(u32, u32)", tables["cased_ranges"], 5, lambda r: "(0x%X, 0x%X)" % (r[0], r[1]))
open(sys.argv[5], "w").write("\n".join(lines).rstrip("\n") + "\n")
fixture = {
  "java_runtime_version": probe["java_runtime_version"], "java_vendor": probe["java_vendor"],
  "probe_sha256": sha("RootLowercaseProbe.java"), "context_probe_sha256": sha("ContextSetsProbe.java"),
  "scalar_fnv1a64": probe["scalar_fnv1a64"], "strings": probe["strings"],
  "enumeration_count": context["enumeration_count"], "enumeration_fnv1a64": context["enumeration_fnv1a64"],
  "random_count": context["random_count"], "random_seed": context["random_seed"], "random_fnv1a64": context["random_fnv1a64"],
  "named": context["named"],
}
json.dump(fixture, open(sys.argv[6], "w"), indent=0)
print("tables lines", len(lines), "strings", len(fixture["strings"]), "named", len(fixture["named"]))
